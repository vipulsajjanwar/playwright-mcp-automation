package framework.reporting.allure;

import framework.config.ReportingConfig;
import framework.reporting.ReportUtils;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;
import java.time.LocalDateTime;
import java.time.format.DateTimeFormatter;
import java.util.Comparator;
import java.util.List;
import java.util.Optional;
import java.util.concurrent.ConcurrentHashMap;
import java.util.concurrent.ConcurrentMap;
import java.util.stream.Stream;

/**
 * Manages unique, timestamped directory paths for Allure test results, reports,
 * and historical data across test suites.
 *
 * Folder Structure:
 * <pre>
 * reports/
 * └── allure/
 *     ├── &lt;SuiteName&gt;_&lt;yyyy-MM-dd_HH-mm-ss&gt;/
 *     │   ├── allure-results/
 *     │   │   └── history/ (copied from previous execution prior to run)
 *     │   ├── allure-report/
 *     │   │   └── history/ (generated by Allure CLI)
 *     │   └── history/     (backup archive)
 * </pre>
 */
public final class ReportPathManager {

    private static final Logger logger = LoggerFactory.getLogger(ReportPathManager.class);
    private static final DateTimeFormatter TIMESTAMP_FORMATTER = DateTimeFormatter.ofPattern("yyyy-MM-dd_HH-mm-ss");

    private static final ConcurrentMap<String, ExecutionPaths> SUITE_PATHS_MAP = new ConcurrentHashMap<>();
    private static volatile ExecutionPaths latestExecutionPaths;

    public record ExecutionPaths(
            String suiteName,
            String timestamp,
            Path executionDir,
            Path resultsDir,
            Path reportDir,
            Path historyBackupDir
    ) {}

    private ReportPathManager() {}

    /**
     * Initializes a unique execution directory structure for the given suite.
     *
     * @param rawSuiteName The name of the test suite (e.g. "UserSuite", "AdminSuite")
     * @return ExecutionPaths record containing all resolved paths
     */
    public static synchronized ExecutionPaths initializeExecutionPaths(String rawSuiteName) {
        String suiteName = (rawSuiteName == null || rawSuiteName.isBlank()) ? "DefaultSuite" : ReportUtils.sanitizeFilename(rawSuiteName);
        String timestamp = LocalDateTime.now().format(TIMESTAMP_FORMATTER);
        String folderName = suiteName + "_" + timestamp;

        Path basePath = getBaseAllurePath();
        Path executionDir = basePath.resolve(folderName);
        Path resultsDir = executionDir.resolve("allure-results");
        Path reportDir = executionDir.resolve("allure-report");
        Path historyBackupDir = executionDir.resolve("history");

        try {
            Files.createDirectories(resultsDir);
            Files.createDirectories(historyBackupDir);
            logger.info("Initialized Allure execution paths: Suite='{}' -> '{}'", suiteName, executionDir);
        } catch (IOException e) {
            logger.error("Failed to create Allure execution directories at: {}", executionDir, e);
        }

        ExecutionPaths paths = new ExecutionPaths(suiteName, timestamp, executionDir, resultsDir, reportDir, historyBackupDir);
        SUITE_PATHS_MAP.put(suiteName, paths);
        latestExecutionPaths = paths;

        // Set system property so Allure Java Commons / TestNG reporter defaults to this directory
        System.setProperty("allure.results.directory", resultsDir.toAbsolutePath().toString());

        return paths;
    }

    /**
     * Gets the current base path where all suite execution directories are stored.
     * Configurable via 'allure.base.path', default is 'reports/allure'.
     */
    public static Path getBaseAllurePath() {
        String configured = ReportingConfig.getAllureBasePath();
        if (configured == null || configured.isBlank()) {
            configured = "reports/allure";
        }
        return Paths.get(configured).toAbsolutePath().normalize();
    }

    /**
     * Gets execution paths for a specific suite. If not initialized, initializes with defaults.
     */
    public static ExecutionPaths getExecutionPaths(String suiteName) {
        if (suiteName != null && SUITE_PATHS_MAP.containsKey(suiteName)) {
            return SUITE_PATHS_MAP.get(suiteName);
        }
        if (latestExecutionPaths != null) {
            return latestExecutionPaths;
        }
        return initializeExecutionPaths(suiteName);
    }

    /**
     * Gets the latest active or initialized execution paths.
     */
    public static ExecutionPaths getLatestExecutionPaths() {
        if (latestExecutionPaths == null) {
            return initializeExecutionPaths("DefaultSuite");
        }
        return latestExecutionPaths;
    }

    /**
     * Gets the current results directory path.
     */
    public static Path getResultsDir() {
        return getLatestExecutionPaths().resultsDir();
    }

    /**
     * Gets the current report directory path.
     */
    public static Path getReportDir() {
        return getLatestExecutionPaths().reportDir();
    }

    /**
     * Gets the current history backup directory path.
     */
    public static Path getHistoryBackupDir() {
        return getLatestExecutionPaths().historyBackupDir();
    }

    /**
     * Finds the latest previous execution directory for a suite (or across all suites if none matches).
     *
     * @param suiteName Name of the suite to match
     * @param currentExecutionDir The active execution directory to exclude
     * @return Optional containing the previous execution directory path if found
     */
    public static Optional<Path> findLatestPreviousExecutionDir(String suiteName, Path currentExecutionDir) {
        Path basePath = getBaseAllurePath();
        if (!Files.exists(basePath) || !Files.isDirectory(basePath)) {
            return Optional.empty();
        }

        try (Stream<Path> stream = Files.list(basePath)) {
            List<Path> dirs = stream
                    .filter(Files::isDirectory)
                    .filter(dir -> currentExecutionDir == null || !dir.toAbsolutePath().equals(currentExecutionDir.toAbsolutePath()))
                    .sorted(Comparator.comparing(Path::getFileName).reversed())
                    .toList();

            if (dirs.isEmpty()) {
                return Optional.empty();
            }

            // 1. First priority: match execution folder belonging to the same suite name (e.g. UserSuite_*)
            if (suiteName != null && !suiteName.isBlank()) {
                String prefix = ReportUtils.sanitizeFilename(suiteName) + "_";
                Optional<Path> suiteMatch = dirs.stream()
                        .filter(dir -> dir.getFileName().toString().startsWith(prefix))
                        .findFirst();

                if (suiteMatch.isPresent()) {
                    return suiteMatch;
                }
            }

            // 2. Second priority: fallback to the latest run directory in reports/allure
            return Optional.of(dirs.get(0));

        } catch (IOException e) {
            logger.warn("Error scanning previous Allure execution directories in {}: {}", basePath, e.getMessage());
            return Optional.empty();
        }
    }
}
